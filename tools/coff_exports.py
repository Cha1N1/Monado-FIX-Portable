#!/usr/bin/env python3
"""Export a Windows release runtime's symbols to the game code library it loads.

The game code library (tools/gamebuild.py) calls the runtime's functions and reads its data, so xcde.exe must export
them. zig's linker supports neither --export-all-symbols nor --out-implib, so this does what __declspec(dllexport)
does: it reads the symbol tables of the runtime's COFF objects and writes a C file whose .drectve section asks the
linker to export every global symbol they define (data marked DATA). tools/pe_implib.py then writes the import library
from the linked executable.

    python tools/coff_exports.py --objects @objects.txt --output exports.c
"""
import argparse
import struct
import sys
from pathlib import Path

IMAGE_SYM_CLASS_EXTERNAL = 2
IMAGE_SCN_CNT_CODE = 0x20
SKIP_PREFIXES = ('.', '__imp_', '__real@', '__xmm@', '__ymm@', '_Z', '??', '$')  # sections, imports, constants, C++


def defined_globals(path):
    data = Path(path).read_bytes()
    machine, sections_count, _, symtab, symbols_count, optional_size, _ = struct.unpack_from('<HHIIIHH', data, 0)
    if machine != 0x8664:
        raise SystemExit(f'{path}: not an x86-64 COFF object')
    characteristics = []
    for i in range(sections_count):
        characteristics.append(struct.unpack_from('<I', data, 20 + optional_size + 40 * i + 36)[0])
    strings = symtab + 18 * symbols_count
    result = []
    i = 0
    while i < symbols_count:
        entry = symtab + 18 * i
        raw, value, section, kind, storage, aux = struct.unpack_from('<8sIhHBB', data, entry)
        if storage == IMAGE_SYM_CLASS_EXTERNAL and section > 0:
            if raw[:4] == b'\0\0\0\0':
                offset = struct.unpack_from('<I', raw, 4)[0]
                name = data[strings + offset:data.index(b'\0', strings + offset)].decode()
            else:
                name = raw.rstrip(b'\0').decode()
            if not name.startswith(SKIP_PREFIXES) and name != 'main':
                result.append((name, not characteristics[section - 1] & IMAGE_SCN_CNT_CODE))
        i += 1 + aux
    return result


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--objects', required=True, nargs='+', help='COFF objects (or @file listing them, ;- or line-separated)')
    ap.add_argument('--output', required=True)
    a = ap.parse_args(argv)
    objects = []
    for item in a.objects:
        if item.startswith('@'):
            text = Path(item[1:]).read_text(encoding='utf-8')
            objects += [p for p in text.replace(';', '\n').splitlines() if p.strip()]
        else:
            objects += [p for p in item.split(';') if p]
    symbols = {}
    for obj in objects:
        for name, is_data in defined_globals(obj):
            symbols[name] = is_data
    if len(symbols) < 100:
        raise SystemExit(f'only {len(symbols)} global symbols in {len(objects)} objects: not the runtime?')
    lines = ['// generated by tools/coff_exports.py: the runtime symbols the game code library links against',
             '__asm__(".section .drectve,\\"yn\\"\\n"']
    for name in sorted(symbols):
        lines.append(f'        ".ascii \\" -export:{name}{",DATA" if symbols[name] else ""}\\"\\n"')
    lines.append('        ".text\\n");')
    Path(a.output).write_text('\n'.join(lines) + '\n', encoding='ascii')
    print(f'{a.output}: {len(symbols)} exports ({sum(symbols.values())} data) from {len(objects)} objects')
    return 0


if __name__ == '__main__':
    sys.exit(main())
